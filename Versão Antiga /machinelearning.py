#===========================================================
# Sistema de Detecção de Vazamentos em Reservatórios
# Modelo Não Supervisionado (Isolation Forest)
#===========================================================

import pandas as pd
import numpy as np
from sklearn.ensemble import IsolationForest
from sklearn.preprocessing import StandardScaler
from datetime import datetime

#===========================================================
# 1) CARREGAR O DATASET
#===========================================================

arquivo = "/dados_reservatorio_2025-11-27_16-00-40.csv"

df = pd.read_csv(arquivo)

print("\n🔎 Primeiras linhas do dataset:")
print(df.head())

#===========================================================
# 2) PRÉ-PROCESSAMENTO
#===========================================================

print("\n🔎 Verificando valores faltantes:")
print(df.isnull().sum())

features = ["leitura_sensor_cm", "nivel_reservatorio_percentual", "taxa_mudanca_visual"]

# Converter para float
for col in features:
    df[col] = pd.to_numeric(df[col], errors="coerce")

# Remove linhas inválidas
df = df.dropna()

X = df[features]

# Padronização
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

#===========================================================
# 3) TREINAMENTO DO MODELO NÃO SUPERVISIONADO
#===========================================================

print("\n🚀 Treinando o modelo...")
modelo = IsolationForest(
    n_estimators=200,
    contamination="auto",
    random_state=42
)
modelo.fit(X_scaled)
print("✅ Modelo treinado com sucesso!")

#===========================================================
# 4) CLASSIFICAÇÃO DOS DADOS
#===========================================================

print("\n⚡ Classificando os dados...")

predicoes = modelo.predict(X_scaled)
df["class_modelo"] = predicoes
df["classificacao"] = df["class_modelo"].map({
    1: "normal",
    -1: "vazamento"
})

#===========================================================
# 5) EXPORTAR RESULTADOS (VERSÃO PC)
#===========================================================

data_hoje = datetime.now().strftime("%Y%m%d_%H%M%S")
arquivo_saida = f"classificacao_resultado_{data_hoje}.csv"
df.to_csv(arquivo_saida, index=False)

print(f"\n📁 Arquivo salvo em: {arquivo_saida}")

#===========================================================
# 6) RESUMO
#===========================================================

print("\n📊 Resumo da Classificação:")
print(df["classificacao"].value_counts())
print("\n🎯 Processo finalizado!")
